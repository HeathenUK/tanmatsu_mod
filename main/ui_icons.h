/**
 * @brief Get icon data by ID
 * @param id Icon ID
 * @return Pointer to icon data, or NULL if invalid ID
 */
static inline const uint8_t *ui_get_icon(ui_icon_id_t id) {
    if (id >= 0 && id < UI_ICON_ID_COUNT) {
        return UI_ICONS[id];
    }
    return NULL;
}

/**
 * @brief Get icon ID for a file extension
 * @param extension File extension (e.g., ".mod", ".xm") or NULL
 * @param is_dir True if this is a directory
 * @param is_parent True if this is parent directory entry (..)
 * @return Appropriate icon ID
 */
static inline ui_icon_id_t ui_get_file_icon_id(const char *extension,
                                                bool is_dir, bool is_parent) {
    if (is_parent) {
        return UI_ICON_ID_PARENT;
    }
    if (is_dir) {
        return UI_ICON_ID_FOLDER;
    }
    if (extension == NULL) {
        return UI_ICON_ID_FILE;
    }

    // Compare case-insensitively
    if (extension[0] == '.') {
        extension++;  // Skip leading dot
    }

    // Check file type
    if ((extension[0] == 'm' || extension[0] == 'M') &&
        (extension[1] == 'o' || extension[1] == 'O') &&
        (extension[2] == 'd' || extension[2] == 'D') &&
        extension[3] == '\0') {
        return UI_ICON_ID_MOD;
    }
    if ((extension[0] == 'x' || extension[0] == 'X') &&
        (extension[1] == 'm' || extension[1] == 'M') &&
        extension[2] == '\0') {
        return UI_ICON_ID_XM;
    }
    if ((extension[0] == 's' || extension[0] == 'S') &&
        (extension[1] == '3') &&
        (extension[2] == 'm' || extension[2] == 'M') &&
        extension[3] == '\0') {
        return UI_ICON_ID_S3M;
    }
    if ((extension[0] == 'i' || extension[0] == 'I') &&
        (extension[1] == 't' || extension[1] == 'T') &&
        extension[2] == '\0') {
        return UI_ICON_ID_IT;
    }

    return UI_ICON_ID_FILE;
}
